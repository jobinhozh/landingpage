/**
 * npm run map: renders the dotted world map for the private page from apps/personal/src/data/travel.json
 * (ISO alpha-2 and numeric code per visited country). Writes apps/personal/src/data/world-map.ts.
 * Build-time only, so the page ships a small static SVG and no map library.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { geoCentroid, geoContains, geoNaturalEarth1 } from "d3-geo";
import type { FeatureCollection, Geometry } from "geojson";
import { feature } from "topojson-client";
import type { Topology } from "topojson-specification";

const W = 360;
const H = 180;
const STEP = 2.4;
const root = new URL("../", import.meta.url);
const visited = JSON.parse(readFileSync(new URL("apps/personal/src/data/travel.json", root), "utf8")) as [
  string,
  string,
][];
const ids = new Set(visited.map(([, n]) => n));

const load = (file: string) => {
  const topo = JSON.parse(
    readFileSync(new URL(`node_modules/world-atlas/${file}`, root), "utf8"),
  ) as Topology;
  return feature(topo, topo.objects.countries!) as unknown as FeatureCollection<Geometry, { name: string }>;
};
const coarse = load("countries-110m.json").features.filter((f) => f.id !== "010"); // without Antarctica
const fine = load("countries-50m.json").features;
const projection = geoNaturalEarth1().fitExtent(
  [
    [2, 2],
    [W - 2, H - 2],
  ],
  { type: "FeatureCollection", features: coarse },
);

const r = (n: number) => Math.round(n * 10) / 10;
let land = "";
let hit = "";
const covered = new Set<string>();
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    const ll = projection.invert!([x, y]);
    if (!ll) continue;
    const f = coarse.find((c) => geoContains(c, ll));
    if (!f) continue;
    const dot = `M${r(x)} ${r(y)}h0`;
    if (ids.has(String(f.id))) {
      hit += dot;
      covered.add(String(f.id));
    } else land += dot;
  }
}

// Countries too small for the dot grid get a pin at their centroid (50m data, else a known point).
const known: Record<string, [number, number]> = {
  GI: [-5.35, 36.14],
  VA: [12.45, 41.9],
  MC: [7.42, 43.73],
  LI: [9.55, 47.16],
};
const pins: [number, number][] = [];
for (const [code, num] of visited) {
  if (covered.has(num) || code === "ENG") continue;
  const f = fine.find((c) => c.id === num);
  const ll = known[code] ?? (f ? (geoCentroid(f) as [number, number]) : undefined);
  if (!ll) throw new Error(`no position for ${code}`);
  const [x, y] = projection(ll)!;
  pins.push([r(x), r(y)]);
}

const out = `// Generated by scripts/world-map.ts (npm run map). Do not edit.
export const worldMap = ${JSON.stringify({ width: W, height: H, land, visited: hit, pins })};
`;
writeFileSync(new URL("apps/personal/src/data/world-map.ts", root), out);
console.log(
  `world map: ${covered.size} countries as dots, ${pins.length} pins, ${(out.length / 1024).toFixed(1)} KB`,
);
